/* bucket_of()
 * Map consensus length to bucket index, matching Python bucket_of().
 */
static int
bucket_of(int clen)
{
  if (clen <=  100) return BUCKET_TINY;
  if (clen <=  300) return BUCKET_SMALL;
  if (clen <   700) return BUCKET_MEDLARGE;
  if (clen <  1500) return BUCKET_LARGE;
  return BUCKET_HUGE;
}


/* ridge_predict()
 * Compute the ridge regression prediction for one target.
 *
 * Formula: raw  = intercept + sum_i coef[i] * (feats[idx_i] - mean[i]) / std[i]
 *          pred = identity(raw) or exp(raw), depending on r->y_transform.
 *
 * For empty (undefined) ridges, returns 0.0. For intercept-only ridges
 * (nfeat==0 but defined==1), returns y_transform(intercept).
 */
static double
ridge_predict(const FastCalRidge *r, const double *feats_full)
{
  double sum = r->intercept;
  int    i;
  for (i = 0; i < r->nfeat; i++)
    {
      int    idx  = cm_FastCalibrate_FeatureIndex(r->fnames[i]);
      double z;
      if (idx < 0) continue;  /* unknown feature name — skip */
      z    = (feats_full[idx] - r->mean[i]) / r->std[i];
      sum += z * r->coef[i];
    }
  switch (r->y_transform)
    {
    case FCRY_EXP:      return exp(sum);
    case FCRY_IDENTITY: /* fallthrough */
    default:            return sum;
    }
}


/* === K = nrandhits/dbsize predictor =====
 * K is now loaded as a ridge model (one per bucket × mode × is_noss), not
 * a hardcoded constant table. This unifies the C code path: λ, μ_extrap,
 * μ_orig, AND K all flow through ridge_predict(). Future bucket updates
 * are JSON swaps with no C changes.
 *
 * The current K models are v4.x→ridge placeholders converted from the
 * historical hardcoded constants (see scratch/cm_localmu_v55integration/
 * build_v4x_K_ridges.py):
 *   - Glocal modes (ECMGC, ECMGI): K = exp(a) * clen^b
 *     encoded as 1-feature ridge with feature=log_clen, coef=b, intercept=a,
 *     y_transform=exp.
 *   - Local modes (ECMLC, ECMLI): K = constant per bucket
 *     encoded as 0-feature ridge with intercept=K, y_transform=identity.
 *
 * Source of v4.x constants: analysis/nrandhits_rfam_all.tsv (4110 calibrated
 * CMs). Per-mode rmse log(K) ≈ 0.28–0.41. Future v5.5+K K-ridges can replace
 * these placeholders via JSON swap once the C feature extractor supports the
 * full v5.5 feature set.
 * ===================================================== */

/* predict_K: predict the cur_eff_dbsize / Z_search density factor K =
 * nrandhits/dbsize for a given (mode, is_noss, bucket, clen, feats).
 *
 * Looks up the appropriate K ridge slot and calls ridge_predict().
 * 'mode' is one of MODE_ECMLC, MODE_ECMLI, MODE_ECMGC, MODE_ECMGI.
 * Returns K in (0, 1] for a properly-defined ridge.
 */
static double
predict_K(int mode, int is_noss, int bucket, const double *feats)
{
  const FastCalRidge *r = is_noss ? &g_models.noss_K[bucket][mode]
                                  : &g_models.str_K [bucket][mode];
  if (!r->defined) return 1.5625e-4;   /* fallback (250/1.6e6); should not happen */
  return ridge_predict(r, feats);
}


/* ===== brief 67: Option-E gated AT-rich predictor =====================
 *
 * cm_fastcal_gc_emit(): corrected consensus-emission GC fraction. Counts ONE
 * consensus emission per node — MATP node -> MP state (pair, marginalized to
 * its two consensus positions), MATL -> ML singlet, MATR -> MR singlet. The
 * MATP-internal ML/MR fallback states are NOT consensus columns and are
 * excluded naturally by walking nodes (cm->ndtype/cm->nodemap) rather than
 * states (this was the brief-051 overcount bug). The struct cm->e[] are
 * emission PROBABILITIES; to match the Python reference (which parses the
 * 3-dp log-odds in the ASCII CM file, brief063_run/gc_emit_v2.py:gc_new) we
 * requantize each prob to 3-dp log-odds vs cm->null and renormalize per state,
 * exactly as extract_str_struct()/extract_composition() do. Each consensus
 * position contributes a distribution summing to 1; gc = (C+G)/(A+C+G+U) over
 * the accumulated marginal mass. *opt_ncons (if non-NULL) returns the
 * consensus-position count, which MUST equal cm->clen.
 *
 * Shared helper: the planned null3 store-both build-out reuses this same
 * corrected gc as its routing gate + delta-lambda feature (brief 67 sec 3).
 * Returns gc in [0,1], or -1.0 if no consensus emission mass.
 */
double
cm_fastcal_gc_emit(const CM_t *cm, int *opt_ncons)
{
  double acc[4] = { 0.0, 0.0, 0.0, 0.0 };
  int    n_cons = 0;
  int    nd, v, a, b, ab;

  for (nd = 0; nd < cm->nodes; nd++)
    {
      if (cm->ndtype[nd] == MATP_nd)
        {
          v = cm->nodemap[nd];
          if (cm->stid[v] != MATP_MP) continue;   /* MP is the first state of a MATP node */
          double p[16], s = 0.0;
          for (ab = 0; ab < 16; ab++) {
            a = ab / 4; b = ab % 4;
            double e  = (double) cm->e[v][ab];
            double nl = (double) cm->null[a] * (double) cm->null[b];
            if (e <= 0.0 || nl <= 0.0) { p[ab] = 0.0; continue; }
            double lo = round(log2(e / nl) * 1000.0) / 1000.0;  /* 3-dp file log-odds */
            p[ab] = nl * exp2(lo);
            s += p[ab];
          }
          if (s <= 0.0) continue;
          /* renormalize over the 16 pairs, then marginalize to left+right
           * (index ab = 4*left + right) -> total mass 2, one per position */
          for (a = 0; a < 4; a++)
            for (b = 0; b < 4; b++) {
              double pv = p[4 * a + b] / s;
              acc[a] += pv;   /* left  consensus position */
              acc[b] += pv;   /* right consensus position */
            }
          n_cons += 2;
        }
      else if (cm->ndtype[nd] == MATL_nd || cm->ndtype[nd] == MATR_nd)
        {
          v = cm->nodemap[nd];   /* ML (MATL) or MR (MATR) is the first state */
          double p[4], s = 0.0;
          for (a = 0; a < 4; a++) {
            double e  = (double) cm->e[v][a];
            double nl = (double) cm->null[a];
            if (e <= 0.0 || nl <= 0.0) { p[a] = 0.0; continue; }
            double lo = round(log2(e / nl) * 1000.0) / 1000.0;
            p[a] = nl * exp2(lo);
            s += p[a];
          }
          if (s <= 0.0) continue;
          for (a = 0; a < 4; a++) acc[a] += p[a] / s;
          n_cons += 1;
        }
    }

  if (opt_ncons) *opt_ncons = n_cons;
  double tot = acc[0] + acc[1] + acc[2] + acc[3];
  if (tot <= 0.0) return -1.0;
  return (acc[1] + acc[2]) / tot;
}

