/* bucket_of()
 * Map consensus length to bucket index, matching Python bucket_of().
 */
static int
bucket_of(int clen)
{
  if (clen <=  100) return BUCKET_TINY;
  if (clen <=  300) return BUCKET_SMALL;
  if (clen <   700) return BUCKET_MEDLARGE;
  if (clen <  1500) return BUCKET_LARGE;
  return BUCKET_HUGE;
}


/* ridge_predict()
 * Compute the ridge regression prediction for one target.
 *
 * Formula: raw  = intercept + sum_i coef[i] * (feats[idx_i] - mean[i]) / std[i]
 *          pred = identity(raw) or exp(raw), depending on r->y_transform.
 *
 * For empty (undefined) ridges, returns 0.0. For intercept-only ridges
 * (nfeat==0 but defined==1), returns y_transform(intercept).
 */
static double
ridge_predict(const FastCalRidge *r, const double *feats_full)
{
  double sum = r->intercept;
  int    i;
  for (i = 0; i < r->nfeat; i++)
    {
      int    idx  = cm_FastCalibrate_FeatureIndex(r->fnames[i]);
      double z;
      if (idx < 0) continue;  /* unknown feature name — skip */
      z    = (feats_full[idx] - r->mean[i]) / r->std[i];
      sum += z * r->coef[i];
    }
  switch (r->y_transform)
    {
    case FCRY_EXP:      return exp(sum);
    case FCRY_IDENTITY: /* fallthrough */
    default:            return sum;
    }
}


/* === K = nrandhits/dbsize predictor =====
 * K is now loaded as a ridge model (one per bucket × mode × is_noss), not
 * a hardcoded constant table. This unifies the C code path: λ, μ_extrap,
 * μ_orig, AND K all flow through ridge_predict(). Future bucket updates
 * are JSON swaps with no C changes.
 *
 * The current K models are v4.x→ridge placeholders converted from the
 * historical hardcoded constants (see scratch/cm_localmu_v55integration/
 * build_v4x_K_ridges.py):
 *   - Glocal modes (ECMGC, ECMGI): K = exp(a) * clen^b
 *     encoded as 1-feature ridge with feature=log_clen, coef=b, intercept=a,
 *     y_transform=exp.
 *   - Local modes (ECMLC, ECMLI): K = constant per bucket
 *     encoded as 0-feature ridge with intercept=K, y_transform=identity.
 *
 * Source of v4.x constants: analysis/nrandhits_rfam_all.tsv (4110 calibrated
 * CMs). Per-mode rmse log(K) ≈ 0.28–0.41. Future v5.5+K K-ridges can replace
 * these placeholders via JSON swap once the C feature extractor supports the
 * full v5.5 feature set.
 * ===================================================== */

/* predict_K: predict the cur_eff_dbsize / Z_search density factor K =
 * nrandhits/dbsize for a given (mode, is_noss, bucket, clen, feats).
 *
 * Looks up the appropriate K ridge slot and calls ridge_predict().
 * 'mode' is one of MODE_ECMLC, MODE_ECMLI, MODE_ECMGC, MODE_ECMGI.
 * Returns K in (0, 1] for a properly-defined ridge.
 */
static double
predict_K(int mode, int is_noss, int bucket, const double *feats)
{
  const FastCalRidge *r = is_noss ? &g_models.noss_K[bucket][mode]
                                  : &g_models.str_K [bucket][mode];
  if (!r->defined) return 1.5625e-4;   /* fallback (250/1.6e6); should not happen */
  return ridge_predict(r, feats);
}


/* cm_FastCalibrate()
 * Predict ECM parameters (λ, μ_extrap, μ_orig) for all 4 ECM modes and
 * populate cm->expA[0..EXP_NMODES-1] in place.
 *
 * Models are lazy-loaded from compiled-in JSON on first call.
 * Returns eslOK on success, eslFAIL if features can't be extracted or a
 * required ridge is empty (nfeat == 0).
 */
int
cm_FastCalibrate(CM_t *cm)
{
  double        feats[FAST_CAL_NFEAT];
  int           bucket;
  int           is_noss;
  int           mode, nd, i;
  int           status;

  /* Lazy model load */
  if (!g_models.loaded)
    {
      if ((status = load_models()) != eslOK) return eslFAIL;
    }

  /* Extract all 27 features */
  if ((status = cm_FastCalibrate_ExtractFeatures(cm, feats)) != eslOK)
    return eslFAIL;

  /* Detect NOSS: no MATP nodes means no base pairs */
  is_noss = 1;
  for (nd = 0; nd < cm->nodes; nd++)
    if (cm->ndtype[nd] == MATP_nd) { is_noss = 0; break; }

  /* Pick bucket, with NOSS huge/large fallback to medlarge */
  bucket = bucket_of(cm->clen);
  if (is_noss && bucket >= BUCKET_LARGE)
    bucket = BUCKET_MEDLARGE;

  /* Allocate cm->expA if needed */
  if (cm->expA == NULL)
    {
      ESL_ALLOC(cm->expA, sizeof(ExpInfo_t *) * EXP_NMODES);
      for (i = 0; i < EXP_NMODES; i++) cm->expA[i] = NULL;
    }
  for (i = 0; i < EXP_NMODES; i++)
    if (cm->expA[i] == NULL)
      {
        cm->expA[i] = CreateExpInfo();
        if (cm->expA[i] == NULL) goto ERROR;
      }

  /* Predict for each ECM mode.
   * Infernal mode indices: EXP_CM_GC=0, EXP_CM_GI=1, EXP_CM_LC=2, EXP_CM_LI=3.
   * Our internal MODE_ECMLC/GC/LI/GI indices map to those via the enum.
   * We iterate over all 4 modes by Infernal's mode indices.
   *
   * Mode name order in models: ECMLC=0, ECMLI=1, ECMGC=2, ECMGI=3 (from JSON parse).
   * Infernal's: EXP_CM_GC=0, EXP_CM_GI=1, EXP_CM_LC=2, EXP_CM_LI=3.
   * Map: Infernal EXP_CM_LC → MODE_ECMLC, EXP_CM_LI → MODE_ECMLI, etc.
   */
  static const int inf_to_model_mode[EXP_NMODES] = {
    MODE_ECMGC,  /* EXP_CM_GC = 0 */
    MODE_ECMGI,  /* EXP_CM_GI = 1 */
    MODE_ECMLC,  /* EXP_CM_LC = 2 */
    MODE_ECMLI,  /* EXP_CM_LI = 3 */
  };

  for (i = 0; i < EXP_NMODES; i++)
    {
      mode = inf_to_model_mode[i];

      FastCalRidge *r_lam, *r_mue, *r_muo;
      if (is_noss) {
        r_lam = &g_models.noss_lambda   [bucket][mode];
        r_mue = &g_models.noss_mu_extrap[bucket][mode];
        r_muo = &g_models.noss_mu_orig  [bucket][mode];
      } else {
        r_lam = &g_models.str_lambda   [bucket][mode];
        r_mue = &g_models.str_mu_extrap[bucket][mode];
        r_muo = &g_models.str_mu_orig  [bucket][mode];
      }

      if (r_lam->nfeat == 0) return eslFAIL;  /* no ridge for this slot */

      double lam = ridge_predict(r_lam, feats);
      double mu_e = (r_mue->nfeat > 0) ? ridge_predict(r_mue, feats) : 0.0;
      double mu_o = (r_muo->nfeat > 0) ? ridge_predict(r_muo, feats) : 0.0;

      /* Predict K = nrandhits/dbsize via the K ridge.
       * In cmsearch, cur_eff_dbsize = (Z_search/dbsize) * nrandhits, so
       * K controls the absolute E-value scale. The K ridge is loaded as
       * one of the embedded JSONs (v4.x→ridge placeholder; future v5.5+K
       * swap is JSON-only). Local-mode K ridges are intercept-only;
       * glocal-mode K ridges are clen power laws (feature=log_clen).
       */
      double K_pred = predict_K(mode, is_noss, bucket, feats);
      int    nrh    = (int) round(K_pred * 1.6e6);
      if (nrh < 1) nrh = 1;

      /* Conventional calibration metadata */
      SetExpInfo(cm->expA[i], lam, mu_o, 1.6e6, nrh, 0.01);
      /* Override mu_extrap with the directly-predicted value
       * (SetExpInfo would recompute it from mu_orig/lambda/tailp). */
      if (r_mue->nfeat > 0)
        cm->expA[i]->mu_extrap = mu_e;
    }

  cm->flags |= CMH_EXPTAIL_STATS;

  /* Refine local-mode mu via mini-simulation (cm_LocalMu).
   * Overrides regression mu_extrap/mu_orig for ECMLC and ECMLI.
   * Controlled by g_localmu_* globals set from cmbuild options.
   */
  if (g_localmu_on) {
    char   localmu_errbuf[eslERRBUFSIZE];
    ESL_RANDOMNESS *localmu_rng = esl_randomness_Create(g_localmu_seed);
    if (localmu_rng == NULL) { status = eslEMEM; goto ERROR; }
    status = cm_LocalMu(cm, localmu_rng, g_localmu_N, g_localmu_wcap, localmu_errbuf);
    esl_randomness_Destroy(localmu_rng);
    if (status != eslOK) {
      /* Surface the error */
      fprintf(stderr, "cm_LocalMu() failed: %s\n", localmu_errbuf);
      return eslFAIL;
    }
  }

  return eslOK;

 ERROR:
  return eslEMEM;
}


/* cm_FastCalibrateCleanup()
 * Free all model memory. Idempotent.
 */
void
cm_FastCalibrateCleanup(void)
{
  int b, m;
  if (!g_models.loaded) return;
  for (b = 0; b < N_BUCKETS; b++)
    for (m = 0; m < N_MODES; m++)
      {
        ridge_free(&g_models.str_lambda    [b][m]);
        ridge_free(&g_models.str_mu_extrap [b][m]);
        ridge_free(&g_models.str_mu_orig   [b][m]);
        ridge_free(&g_models.str_K         [b][m]);
        ridge_free(&g_models.noss_lambda   [b][m]);
        ridge_free(&g_models.noss_mu_extrap[b][m]);
        ridge_free(&g_models.noss_mu_orig  [b][m]);
        ridge_free(&g_models.noss_K        [b][m]);
      }
  g_models.loaded = 0;
}


/* =========================================================================
 * cm_LocalMu(): fixed-lambda mini-sim for local mu_extrap estimation.
 *
 * Background (from study of cmcalibrate.c):
 *   a. Random sequence generation: SampleGenomicSequenceFromHMM() with a
 *      5-state GC-content HMM (CreateGenomicHMM), mimicking genomic composition.
 *   b. QDB setup: cm->config_opts |= CM_CONFIG_QDB, beta1=beta2=1e-15, then
 *      cm_Configure(cm, errbuf, -1) which calls CalculateQueryDependentBands.
 *      Must use 1e-15 (cmcalibrate default); looser beta inflates scores by ~7 bits.
 *   c. Local CYK: FastCYKScan(cm, smx, SMX_QDB2_LOOSE, ...) with NULL3 on.
 *      Local Inside: FastIInsideScan(cm, smx, SMX_QDB2_LOOSE, ...) with NULL3 on.
 *      The CM_SEARCH_INSIDE flag toggles CYK vs Inside in cmcalibrate's
 *      process_search_workunit(); we handle CYK and Inside separately here.
 *   d. NULL3 correction IS applied (CM_SEARCH_NULL3 is set by default in
 *      cmcalibrate for calibration). We enable it here as well.
 *   e. We score one sequence at a time (L=2*W_eff) and record the best-hit
 *      score per sequence. If no hit is found, use -1e9 as sentinel.
 *      (cmcalibrate searches 10 Kb chunks; our mini-sim uses 2*W_eff chunks
 *      as validated in 25_1218: mean ratio 1.00 at L=2W for local modes.)
 */

/* cm_LocalMu()
 * Fixed-lambda mini-simulation for local mu_extrap estimation.
 * Generates N random genomic-HMM sequences of length 2*W_eff (where
 * W_eff = capped W if use_wcap, else cm->W). Scores each with local
 * CYK + local Inside + QDBs at beta=1e-15. Computes mu_extrap and
 * mu_orig from fixed-lambda MLE on the best-hit-per-seq scores.
 * Overwrites cm->expA[EXP_CM_LC]->mu_extrap, ->mu_orig
 *            cm->expA[EXP_CM_LI]->mu_extrap, ->mu_orig
 * Glocal mode ExpInfo and lambda are unchanged.
 */
int
cm_LocalMu(CM_t *cm, ESL_RANDOMNESS *rng, int N, int use_wcap, char *errbuf)
{
  int     status;
  int     i;
  CM_t   *lcm      = NULL;   /* cloned CM, configured for local mode */

  /* HMM parameters for genomic sequence generation */
  double  *ghmm_sA  = NULL;
  double **ghmm_tAA = NULL;
  double **ghmm_eAA = NULL;
  int      ghmm_nstates = 0;

  ESL_DSQ    *dsq      = NULL;
  CM_TOPHITS *th       = NULL;
  float  *cyk_scores   = NULL;   /* growable array of ALL CYK hit scores across N scans */
  float  *ins_scores   = NULL;   /* growable array of ALL Inside hit scores across N scans */
  float  *neg_ls       = NULL;   /* scratch: -lambda * score[i] for log-sum */
  int     n_cyk = 0, alloc_cyk = 0;
  int     n_ins = 0, alloc_ins = 0;
  int     W_eff;
  int     L;
  double  beta_use;

  /* Step 1: Compute W_eff and L */
  if (use_wcap) {
    if      (cm->W > 3000)    W_eff = ESL_MIN(cm->W, 300);
    else if (cm->clen > 1000) W_eff = ESL_MIN(cm->W, ESL_MAX(200, cm->W / 10));
    else                      W_eff = ESL_MIN(cm->W, ESL_MIN(400, ESL_MAX(200, cm->W / 4)));
  } else {
    W_eff = cm->W;
  }
  L = 2 * W_eff;
  if (L < cm->clen) L = cm->clen;   /* safety floor for tiny CMs */
  if (g_localmu_L > 0) L = g_localmu_L;   /* user override (e.g., 10000 to mimic cmcalibrate) */

  /* Resolve N. If user set --localmu-N, honor it. Otherwise auto-pick by
   * clen using a power-law fit: N ≈ 7500 * clen^-0.8, clamped to [20,200].
   * Anchors: clen<=80 → 200; clen=500 → ~52; clen=1000 → ~30; clen=1500 → ~22.
   * Validated in v11/v12 sweeps: med|Δμ| stays ≤1 bit across the full panel
   * with this rule, while large CMs see ~9-17x runtime reduction.
   */
  if (N <= 0) {
    int Nauto = (int)(7500.0 * pow((double) cm->clen, -0.8) + 0.5);
    if (Nauto < 20)  Nauto = 20;
    if (Nauto > 200) Nauto = 200;
    N = Nauto;
  }

  /* Resolve QDB beta. If user set --localmu-beta, honor it. Otherwise pick
   * by clen: small CMs (clen<200) need tight prob (β=1e-15) for accurate
   * mu_extrap; large CMs are insensitive to β and tolerate β=1e-3 for ~5x
   * scan speedup (validated in v7 sweep over 5 CMs / 5 β values).
   */
  beta_use = (g_localmu_beta > 0.0) ? g_localmu_beta
                                     : (cm->clen < 200 ? 1e-15 : 1e-3);

  /* Step 2: Clone the CM and prepare the clone for fresh local-mode configuration.
   *
   * Background: by the time cm_LocalMu() is called from cm_FastCalibrate(),
   * the original CM has been fully configured in global mode by cmbuild's
   * configure_model() → cm_Configure(). This means CM_IS_CONFIGURED, CMH_BITS,
   * CMH_CP9, CMH_MLP7, CMH_LOCAL_BEGIN/END flags are set, and cp9/smx/hb_mx
   * etc. are non-NULL. cm_Configure() calls cm_nonconfigured_Verify() which
   * rejects any configured CM. So we must strip all configuration state from
   * the clone to make it look like a freshly-built unconfigured CM.
   */
  if ((status = cm_Clone(cm, errbuf, &lcm)) != eslOK) goto ERROR;

  /* Strip all configuration state from clone: free matrices, CP9, scan mx. */
  /* HMM-banded matrices */
  if (lcm->hb_mx    != NULL) { cm_hb_mx_Destroy(lcm->hb_mx);                 lcm->hb_mx    = NULL; }
  if (lcm->hb_omx   != NULL) { cm_hb_mx_Destroy(lcm->hb_omx);                lcm->hb_omx   = NULL; }
  if (lcm->hb_emx   != NULL) { cm_hb_emit_mx_Destroy(lcm->hb_emx);           lcm->hb_emx   = NULL; }
  if (lcm->hb_shmx  != NULL) { cm_hb_shadow_mx_Destroy(lcm->hb_shmx);        lcm->hb_shmx  = NULL; }
  /* Truncated HMM-banded matrices */
  if (lcm->trhb_mx  != NULL) { cm_tr_hb_mx_Destroy(lcm->trhb_mx);            lcm->trhb_mx  = NULL; }
  if (lcm->trhb_omx != NULL) { cm_tr_hb_mx_Destroy(lcm->trhb_omx);           lcm->trhb_omx = NULL; }
  if (lcm->trhb_emx != NULL) { cm_tr_hb_emit_mx_Destroy(lcm->trhb_emx);      lcm->trhb_emx = NULL; }
  if (lcm->trhb_shmx!= NULL) { cm_tr_hb_shadow_mx_Destroy(lcm->trhb_shmx);   lcm->trhb_shmx= NULL; }
  /* Non-banded CM matrices */
  if (lcm->nb_mx    != NULL) { cm_mx_Destroy(lcm->nb_mx);                     lcm->nb_mx    = NULL; }
  if (lcm->nb_omx   != NULL) { cm_mx_Destroy(lcm->nb_omx);                    lcm->nb_omx   = NULL; }
  if (lcm->nb_emx   != NULL) { cm_emit_mx_Destroy(lcm->nb_emx);               lcm->nb_emx   = NULL; }
  if (lcm->nb_shmx  != NULL) { cm_shadow_mx_Destroy(lcm->nb_shmx);            lcm->nb_shmx  = NULL; }
  /* Truncated non-banded matrices */
  if (lcm->trnb_mx  != NULL) { cm_tr_mx_Destroy(lcm->trnb_mx);                lcm->trnb_mx  = NULL; }
  if (lcm->trnb_omx != NULL) { cm_tr_mx_Destroy(lcm->trnb_omx);               lcm->trnb_omx = NULL; }
  if (lcm->trnb_emx != NULL) { cm_tr_emit_mx_Destroy(lcm->trnb_emx);          lcm->trnb_emx = NULL; }
  if (lcm->trnb_shmx!= NULL) { cm_tr_shadow_mx_Destroy(lcm->trnb_shmx);       lcm->trnb_shmx= NULL; }
  /* Scan matrices */
  if (lcm->smx      != NULL) { cm_scan_mx_Destroy(lcm, lcm->smx);             lcm->smx      = NULL; }
  if (lcm->trsmx    != NULL) { cm_tr_scan_mx_Destroy(lcm, lcm->trsmx);        lcm->trsmx    = NULL; }
  /* CP9 HMMs and related */
  if (lcm->cp9      != NULL) { FreeCPlan9(lcm->cp9);                           lcm->cp9      = NULL; }
  if (lcm->Lcp9     != NULL) { FreeCPlan9(lcm->Lcp9);                          lcm->Lcp9     = NULL; }
  if (lcm->Rcp9     != NULL) { FreeCPlan9(lcm->Rcp9);                          lcm->Rcp9     = NULL; }
  if (lcm->Tcp9     != NULL) { FreeCPlan9(lcm->Tcp9);                          lcm->Tcp9     = NULL; }
  if (lcm->cp9map   != NULL) { FreeCP9Map(lcm->cp9map);                        lcm->cp9map   = NULL; }
  if (lcm->cp9b     != NULL) { FreeCP9Bands(lcm->cp9b);                        lcm->cp9b     = NULL; }
  if (lcm->cp9_mx   != NULL) { FreeCP9Matrix(lcm->cp9_mx);                     lcm->cp9_mx   = NULL; }
  if (lcm->cp9_bmx  != NULL) { FreeCP9Matrix(lcm->cp9_bmx);                    lcm->cp9_bmx  = NULL; }
  /* p7 HMMs */
  if (lcm->mlp7     != NULL) { p7_hmm_Destroy(lcm->mlp7);                      lcm->mlp7     = NULL; }
  /* Truncation penalties and consensus */
  if (lcm->trp      != NULL) { cm_tr_penalties_Destroy(lcm->trp);              lcm->trp      = NULL; }
  if (lcm->cmcons   != NULL) { FreeCMConsensus(lcm->cmcons);                   lcm->cmcons   = NULL; }

  /* Reset flags: clear all that cm_nonconfigured_Verify() checks for absence.
   * Keep CMH_HASBITS only if needed; we're re-running CMLogoddsify in
   * cm_Configure(), so we drop it and let configure recompute. */
  lcm->flags &= ~(CMH_BITS | CMH_MLP7 | CMH_LOCAL_BEGIN | CMH_LOCAL_END |
                  CMH_CP9  | CMH_CP9_TRUNC | CM_EMIT_NO_LOCAL_BEGINS |
                  CM_EMIT_NO_LOCAL_ENDS | CM_IS_CONFIGURED);
  /* Clear config/search opts from original configuration; we'll set fresh ones */
  lcm->config_opts = 0;
  lcm->search_opts = 0;

  /* Reset qdbinfo: set beta to 1e-15 (same as cmcalibrate default) and mark
   * as INIT so cm_Configure() will recalculate bands at beta=1e-15.
   * The dmin/dmax arrays in the clone will be recomputed by cm_Configure().
   */
  if (lcm->qdbinfo != NULL) {
    lcm->qdbinfo->beta1 = beta_use;
    lcm->qdbinfo->beta2 = beta_use;
    lcm->qdbinfo->setby = CM_QDBINFO_SETBY_INIT;
    /* Reset dmin/dmax to initial values (0 and clen*2) */
    esl_vec_ISet(lcm->qdbinfo->dmin1, lcm->M, 0);
    esl_vec_ISet(lcm->qdbinfo->dmax1, lcm->M, lcm->clen * 2);
    esl_vec_ISet(lcm->qdbinfo->dmin2, lcm->M, 0);
    esl_vec_ISet(lcm->qdbinfo->dmax2, lcm->M, lcm->clen * 2);
  }

  /* Restore W and W_setby to initial (INIT) so cm_Configure will recompute W
   * from QDB bands (or use W_eff if we pass it as W_from_cmdline).
   */
  lcm->W_setby = CM_W_SETBY_INIT;

  /* Also restore the original (global-mode) transition probabilities, since
   * the original CM was configured with local begins/ends which modify the
   * t[] arrays. We need clean global probs for cm_Configure() to start from.
   *
   * Actually: cmbuild configures in GLOBAL mode (no CM_CONFIG_LOCAL), so
   * CMH_LOCAL_BEGIN/END should already be cleared and t[] should be global.
   * Just assert this is the case (if these flags are set, we'd need to
   * de-localize first, which is not implemented here).
   */
  if (cm->flags & CMH_LOCAL_BEGIN) {
    ESL_FAIL(eslEINCOMPAT, errbuf, "cm_LocalMu(): original CM has local begins set; can't unconfigure clone");
  }

  /* Set up local configuration flags on the clone */
  lcm->config_opts |= CM_CONFIG_LOCAL;
  lcm->config_opts |= CM_CONFIG_HMMLOCAL;
  lcm->config_opts |= CM_CONFIG_HMMEL;
  lcm->config_opts |= CM_CONFIG_QDB;
  lcm->config_opts |= CM_CONFIG_SCANMX;
  lcm->search_opts |= CM_SEARCH_QDB;
  lcm->search_opts |= CM_SEARCH_NULL3;
  lcm->search_opts |= CM_SEARCH_NOALIGN;

  /* Set QDB beta to 1e-15 on clone (matches cmcalibrate default) */
  lcm->qdbinfo->beta1 = beta_use;
  lcm->qdbinfo->beta2 = beta_use;

  /* Configure the clone (builds CP9, QDBs, scan matrix, etc.).
   * Pass W_eff as W_from_cmdline in both cases:
   *   use_wcap=1: W_eff is the capped value
   *   use_wcap=0: W_eff = cm->W (pass original W to prevent QDB beta from redefining W)
   * This ensures the scan matrix is sized correctly for our sequence length L.
   */
  if ((status = cm_Configure(lcm, errbuf, W_eff)) != eslOK) goto ERROR;

  /* Verify scan matrix was created */
  if (lcm->smx == NULL) {
    ESL_FAIL(eslEINVAL, errbuf, "cm_LocalMu(): clone CM scan matrix is NULL after cm_Configure");
  }

  /* Step 3: Create genomic HMM and score arrays.
   *
   * cyk_scores / ins_scores are growable arrays that collect EVERY hit score
   * from EVERY scan (not just the per-sequence-best). This matches what
   * cmcalibrate does: pool all hits across the entire calibration database
   * and fit the EVD tail on the pooled distribution.
   */
  if ((status = CreateGenomicHMM(cm->abc, errbuf, &ghmm_sA, &ghmm_tAA, &ghmm_eAA, &ghmm_nstates)) != eslOK) goto ERROR;

  alloc_cyk = N * 64;   /* initial guess; grows on demand */
  alloc_ins = N * 64;
  ESL_ALLOC(cyk_scores, sizeof(float) * alloc_cyk);
  ESL_ALLOC(ins_scores, sizeof(float) * alloc_ins);

  /* Step 4: Generate and score N sequences; collect ALL hit scores */
  for (i = 0; i < N; i++) {
    int h;

    if ((status = SampleGenomicSequenceFromHMM(rng, cm->abc, errbuf,
                                               ghmm_sA, ghmm_tAA, ghmm_eAA,
                                               ghmm_nstates, L, &dsq)) != eslOK) goto ERROR;

    /* Local CYK scan */
    lcm->search_opts &= ~CM_SEARCH_INSIDE;
    th = cm_tophits_Create();
    if (th == NULL) { status = eslEMEM; goto ERROR; }
    if ((status = FastCYKScan(lcm, errbuf, lcm->smx,
                              SMX_QDB2_LOOSE,
                              dsq, 1, L,
                              -eslINFINITY,
                              th,
                              (lcm->search_opts & CM_SEARCH_NULL3) ? TRUE : FALSE,
                              0., NULL, NULL, NULL, NULL)) != eslOK) goto ERROR;
    if (n_cyk + th->N > alloc_cyk) {
      while (n_cyk + th->N > alloc_cyk) alloc_cyk *= 2;
      ESL_REALLOC(cyk_scores, sizeof(float) * alloc_cyk);
    }
    for (h = 0; h < th->N; h++) cyk_scores[n_cyk++] = th->unsrt[h].score;
    cm_tophits_Destroy(th); th = NULL;

    /* Local Inside scan */
    lcm->search_opts |= CM_SEARCH_INSIDE;
    th = cm_tophits_Create();
    if (th == NULL) { status = eslEMEM; goto ERROR; }
    if ((status = FastIInsideScan(lcm, errbuf, lcm->smx,
                                  SMX_QDB2_LOOSE,
                                  dsq, 1, L,
                                  -eslINFINITY,
                                  th,
                                  (lcm->search_opts & CM_SEARCH_NULL3) ? TRUE : FALSE,
                                  0., NULL, NULL, NULL, NULL)) != eslOK) goto ERROR;
    if (n_ins + th->N > alloc_ins) {
      while (n_ins + th->N > alloc_ins) alloc_ins *= 2;
      ESL_REALLOC(ins_scores, sizeof(float) * alloc_ins);
    }
    for (h = 0; h < th->N; h++) ins_scores[n_ins++] = th->unsrt[h].score;
    cm_tophits_Destroy(th); th = NULL;

    free(dsq); dsq = NULL;
  }

  /* Optional: dump pooled hit scores to a TSV (mode\tscore) for offline tailp/MLE analysis */
  if (g_localmu_score_dump != NULL) {
    FILE *dfp = fopen(g_localmu_score_dump, "w");
    if (dfp == NULL) {
      ESL_FAIL(eslEINVAL, errbuf, "cm_LocalMu(): cannot open --localmu-score-dump file '%s'",
               g_localmu_score_dump);
    }
    fprintf(dfp, "mode\tscore\n");
    { int k; for (k = 0; k < n_cyk; k++) fprintf(dfp, "ECMLC\t%.5f\n", cyk_scores[k]); }
    { int k; for (k = 0; k < n_ins; k++) fprintf(dfp, "ECMLI\t%.5f\n", ins_scores[k]); }
    fclose(dfp);
  }

  /* Step 5: Joint (mu, lambda) MLE on the TAIL of the pooled hit-score
   * distribution via esl_gumbel_FitCensored. cmcalibrate fits the tail
   * (not all hits) precisely because CYK/Inside scores have a heavy lower
   * shoulder below the Gumbel mode; FitComplete on all hits gave wildly
   * unstable lambda (v11 experiment, briefs/SUBAGENT_TASK_cm_localmu_v11_REPORT.md
   * — λ off by 30%+ both directions across the panel).
   *
   * Algorithm:
   *   - sort scores descending
   *   - K = round(tailp * n_total) with tailp = 0.01 (top 1%, matching cmcalibrate)
   *   - phi = scores[K]    (censoring threshold = first below-tail score)
   *   - z = n_total - K    (number of censored observations below phi)
   *   - esl_gumbel_FitCensored(scores[0..K-1], K, z, phi, &mu, &lambda)
   *
   * Falls back to legacy fixed-lambda + tail-quantile mu if K < MIN_FIT_K
   * or FitCensored fails.
   */
  {
    const int MIN_FIT_K = 5;     /* need at least this many tail hits */
    const double tailp  = 0.01;
    int       k;
    double   *score_d  = NULL;
    double    mu_fit, lambda_fit, phi;
    int       fit_status;
    int       Kfit, Zcens;

    /* CYK -> EXP_CM_LC */
    if (n_cyk > 0) {
      double lam_reg = cm->expA[EXP_CM_LC]->lambda;  /* regression lambda */
      fit_status = eslFAIL;
      Kfit  = (int) (tailp * (double) n_cyk + 0.5);
      if (Kfit < 1) Kfit = 1;
      if (Kfit >= MIN_FIT_K && Kfit < n_cyk) {
        esl_vec_FSortDecreasing(cyk_scores, n_cyk);
        Zcens = n_cyk - Kfit;
        phi   = (double) cyk_scores[Kfit];   /* threshold: first below-tail score */
        score_d = (double *) malloc(sizeof(double) * Kfit);
        if (score_d != NULL) {
          for (k = 0; k < Kfit; k++) score_d[k] = (double) cyk_scores[k];
          fit_status = esl_gumbel_FitCensored(score_d, Kfit, Zcens, phi,
                                              &mu_fit, &lambda_fit);
          free(score_d); score_d = NULL;
        }
      }
      if (fit_status == eslOK && lambda_fit > 0.0 && lam_reg > 0.0) {
        /* v13: regularize lambda toward regression via geometric mean.
         * v11/v12 raw fits gave wildly variable lambda (max |Δλ|/λ = 23-86%).
         * Geomean(regression, fit) yields max |Δλ|/λ ≤ 20% across the panel
         * while preserving median accuracy. Empirical mu_orig from the tail
         * quantile is robust; mu_extrap derived from geomean lambda. */
        double lambda_v13 = sqrt(lam_reg * lambda_fit);
        double mu_orig    = (double) cyk_scores[Kfit - 1];  /* empirical tailp quantile */
        cm->expA[EXP_CM_LC]->lambda    = lambda_v13;
        cm->expA[EXP_CM_LC]->mu_orig   = mu_orig;
        cm->expA[EXP_CM_LC]->mu_extrap = mu_orig - log(1.0 / tailp) / lambda_v13;
      } else {
        /* Legacy fixed-lambda fallback */
        int    K = (int) (tailp * (double) n_cyk + 0.5);
        float  lambda = (g_localmu_lambda_lc > 0.0) ? (float) g_localmu_lambda_lc
                                                     : (float) cm->expA[EXP_CM_LC]->lambda;
        double mu_orig, mu_extrap;
        if (K < 1) K = 1;
        esl_vec_FSortDecreasing(cyk_scores, n_cyk);
        mu_orig   = (double) cyk_scores[K-1];
        mu_extrap = mu_orig - log(1.0 / tailp) / (double) lambda;
        cm->expA[EXP_CM_LC]->lambda    = (double) lambda;
        cm->expA[EXP_CM_LC]->mu_extrap = mu_extrap;
        cm->expA[EXP_CM_LC]->mu_orig   = mu_orig;
      }
    }
    /* Inside -> EXP_CM_LI */
    if (n_ins > 0) {
      double lam_reg = cm->expA[EXP_CM_LI]->lambda;
      fit_status = eslFAIL;
      Kfit = (int) (tailp * (double) n_ins + 0.5);
      if (Kfit < 1) Kfit = 1;
      if (Kfit >= MIN_FIT_K && Kfit < n_ins) {
        esl_vec_FSortDecreasing(ins_scores, n_ins);
        Zcens = n_ins - Kfit;
        phi   = (double) ins_scores[Kfit];
        score_d = (double *) malloc(sizeof(double) * Kfit);
        if (score_d != NULL) {
          for (k = 0; k < Kfit; k++) score_d[k] = (double) ins_scores[k];
          fit_status = esl_gumbel_FitCensored(score_d, Kfit, Zcens, phi,
                                              &mu_fit, &lambda_fit);
          free(score_d); score_d = NULL;
        }
      }
      if (fit_status == eslOK && lambda_fit > 0.0 && lam_reg > 0.0) {
        double lambda_v13 = sqrt(lam_reg * lambda_fit);
        double mu_orig    = (double) ins_scores[Kfit - 1];
        cm->expA[EXP_CM_LI]->lambda    = lambda_v13;
        cm->expA[EXP_CM_LI]->mu_orig   = mu_orig;
        cm->expA[EXP_CM_LI]->mu_extrap = mu_orig - log(1.0 / tailp) / lambda_v13;
      } else {
        /* Legacy fixed-lambda fallback */
        int    K = (int) (tailp * (double) n_ins + 0.5);
        float  lambda = (g_localmu_lambda_li > 0.0) ? (float) g_localmu_lambda_li
                                                     : (float) cm->expA[EXP_CM_LI]->lambda;
        double mu_orig, mu_extrap;
        if (K < 1) K = 1;
        esl_vec_FSortDecreasing(ins_scores, n_ins);
        mu_orig   = (double) ins_scores[K-1];
        mu_extrap = mu_orig - log(1.0 / tailp) / (double) lambda;
        cm->expA[EXP_CM_LI]->lambda    = (double) lambda;
        cm->expA[EXP_CM_LI]->mu_extrap = mu_extrap;
        cm->expA[EXP_CM_LI]->mu_orig   = mu_orig;
      }
    }
  }

  /* Step 5b (v14 expt A): Optionally override nrandhits for ECMLC/ECMLI with
   * the empirical density measured in the mini-simulation. The K predictor
   * uses bucket-median regressions; this replaces it with per-CM
   * n_total / (N * L) * dbsize_calib for local modes. Glocal unchanged.
   *
   * Hit-rate density K = n_total / (N * L). Stored nrandhits = K * dbsize.
   * dbsize_calib stays at the cmcalibrate convention (1.6e6).
   * For backwards compatibility, gated behind --localmu-K-from-sim.
   */
  if (g_localmu_K_from_sim) {
    double sim_dbsize = (double) N * (double) L;
    double dbsize_calib = 1.6e6;  /* keep cmcalibrate convention for stored dbsize */
    if (n_cyk > 0 && sim_dbsize > 0.0) {
      double K_sim = (double) n_cyk / sim_dbsize;        /* hits per residue */
      int    nrh_sim = (int) (K_sim * dbsize_calib + 0.5);
      if (nrh_sim < 1) nrh_sim = 1;
      cm->expA[EXP_CM_LC]->nrandhits      = nrh_sim;
      cm->expA[EXP_CM_LC]->dbsize         = dbsize_calib;
      cm->expA[EXP_CM_LC]->cur_eff_dbsize = (double) nrh_sim;
    }
    if (n_ins > 0 && sim_dbsize > 0.0) {
      double K_sim = (double) n_ins / sim_dbsize;
      int    nrh_sim = (int) (K_sim * dbsize_calib + 0.5);
      if (nrh_sim < 1) nrh_sim = 1;
      cm->expA[EXP_CM_LI]->nrandhits      = nrh_sim;
      cm->expA[EXP_CM_LI]->dbsize         = dbsize_calib;
      cm->expA[EXP_CM_LI]->cur_eff_dbsize = (double) nrh_sim;
    }
  }

  /* Step 6 & 7: Free temporary memory */
  FreeCM(lcm);
  if (ghmm_sA  != NULL) free(ghmm_sA);
  if (ghmm_tAA != NULL) {
    int s;
    for (s = 0; s < ghmm_nstates; s++) if (ghmm_tAA[s] != NULL) free(ghmm_tAA[s]);
    free(ghmm_tAA);
  }
  if (ghmm_eAA != NULL) {
    int s;
    for (s = 0; s < ghmm_nstates; s++) if (ghmm_eAA[s] != NULL) free(ghmm_eAA[s]);
    free(ghmm_eAA);
  }
  free(cyk_scores);
  free(ins_scores);
  free(neg_ls);
  return eslOK;

 ERROR:
  if (lcm != NULL)      FreeCM(lcm);
  if (ghmm_sA != NULL)  free(ghmm_sA);
  if (ghmm_tAA != NULL) {
    int s;
    for (s = 0; s < ghmm_nstates; s++) if (ghmm_tAA[s] != NULL) free(ghmm_tAA[s]);
    free(ghmm_tAA);
  }
  if (ghmm_eAA != NULL) {
    int s;
    for (s = 0; s < ghmm_nstates; s++) if (ghmm_eAA[s] != NULL) free(ghmm_eAA[s]);
    free(ghmm_eAA);
  }
  if (dsq != NULL)         free(dsq);
  if (th  != NULL)         cm_tophits_Destroy(th);
  if (cyk_scores != NULL)  free(cyk_scores);
  if (ins_scores != NULL)  free(ins_scores);
  if (neg_ls != NULL)      free(neg_ls);
  return status;
}


